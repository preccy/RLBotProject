"""Windows-safe multi-process experience collection.

Why this exists: rlgym-learn 2.0.0's Rust process layer fails on native Windows (each parent UDP socket is
registered with two mio `Poll` instances; mio's IOCP backend rejects the second registration with
`AlreadyExists`, surfacing as `FileExistsError: entity already exists`). The PPO algorithm pieces of
rlgym-learn-algos do not depend on that layer, so we keep them and replace only collection.

Design
------
* `spawn` processes (the only start method on Windows); each worker owns `envs_per_worker` RocketSim
  environments and steps them all on one command. Communication is a multiprocessing Pipe per worker.
* The parent sends every worker its actions first and only then receives, so workers simulate in parallel
  while the parent waits.
* Inference is batched in the parent: one forward pass for all learner-controlled agents, one for the
  frozen-opponent agents (if any).
* Every step is fully synchronous: all experience in an iteration is generated by exactly one policy
  version (no lag, no reuse across iterations).
* Each environment has a fixed role map: in self-play envs every agent is a learner agent; in
  frozen-opponent envs one whole team is driven by a frozen policy and produces NO learner experience.
"""

from __future__ import annotations

import multiprocessing as mp
import os
import time
import traceback
from dataclasses import dataclass, field
from typing import Any, Callable, Dict, List, Optional, Sequence

import numpy as np

from botcore.env import EnvSpec

LEARNER = "learner"
FROZEN = "frozen"


class CollectorError(RuntimeError):
    """A worker crashed or returned an unexpected message."""


# ----------------------------------------------------------------------------------------- worker side
def _worker_main(conn, spec: EnvSpec, seeds: Sequence[int]) -> None:
    import signal

    signal.signal(signal.SIGINT, signal.SIG_IGN)  # Ctrl+C is handled by the parent, which checkpoints and closes us
    os.environ.setdefault("OPENBLAS_NUM_THREADS", "1")
    os.environ.setdefault("OMP_NUM_THREADS", "1")
    try:
        from botcore.env import build_env
        from botcore.scenarios import SCENARIO_KEY

        envs = [build_env(spec, seed) for seed in seeds]
        agents: List[str] = []  # known only after the first reset (the engine creates cars on reset)
        episode_len = [0] * len(envs)
        episode_stats: List[dict] = []

        def reset_all():
            out = []
            for i, env in enumerate(envs):
                obs = env.reset()
                if not agents:
                    agents.extend(env.agents)
                elif list(env.agents) != agents:
                    raise CollectorError(f"env {i} has agents {env.agents}, expected {agents}")
                episode_len[i] = 0
                out.append(np.stack([obs[a] for a in agents]))
            return np.stack(out)

        while True:
            cmd, payload = conn.recv()
            if cmd == "reset":
                conn.send(("ok", (agents, reset_all())))
            elif cmd == "step":
                actions = payload  # int array [n_envs, n_agents]
                obs_rows, rewards, terminated, truncated, final_obs = [], [], [], [], {}
                for i, env in enumerate(envs):
                    obs, rew, term, trunc = env.step({a: actions[i, j:j + 1] for j, a in enumerate(agents)})
                    episode_len[i] += 1
                    is_term = any(term.values())
                    is_trunc = (not is_term) and any(trunc.values())
                    rewards.append([rew[a] for a in agents])
                    terminated.append(is_term)
                    truncated.append(is_trunc)
                    if is_term or is_trunc:
                        final_obs[i] = np.stack([obs[a] for a in agents])
                        state = env.state
                        episode_stats.append({
                            "scenario": env.shared_info.get(SCENARIO_KEY),
                            "length": episode_len[i],
                            "terminated": is_term,
                            "scoring_team": state.scoring_team if is_term else None,
                        })
                        obs = env.reset()
                        episode_len[i] = 0
                    obs_rows.append(np.stack([obs[a] for a in agents]))
                obs_out = np.stack(obs_rows)
                conn.send(("ok", (obs_out, np.asarray(rewards, dtype=np.float32),
                                  np.asarray(terminated), np.asarray(truncated), final_obs)))
            elif cmd == "stats":
                reward_stats = [env.reward_fn.pop_stats() for env in envs]
                conn.send(("ok", (reward_stats, episode_stats)))
                episode_stats = []
            elif cmd == "close":
                for env in envs:
                    env.close()
                conn.send(("ok", None))
                break
            else:
                raise CollectorError(f"unknown command {cmd!r}")
    except EOFError:
        pass  # parent went away
    except BaseException:
        try:
            conn.send(("error", traceback.format_exc()))
        except Exception:
            pass
    finally:
        conn.close()


# ----------------------------------------------------------------------------------------- parent side
@dataclass
class StepResult:
    obs: np.ndarray  # [n_envs, n_agents, obs] observations to act on next (post-reset where an episode ended)
    rewards: np.ndarray  # [n_envs, n_agents]
    terminated: np.ndarray  # [n_envs] true terminal state (goal)
    truncated: np.ndarray  # [n_envs] artificial cut (timeout), value must be bootstrapped
    final_obs: Dict[int, np.ndarray]  # env index -> [n_agents, obs] last observation of the ended episode


class Collector:
    """Owns the worker processes and exposes a vectorised step over all environments."""

    def __init__(self, spec: EnvSpec, n_workers: int, envs_per_worker: int, seed: int,
                 start_timeout: float = 120.0):
        self.spec = spec
        self.n_workers = n_workers
        self.envs_per_worker = envs_per_worker
        self.n_envs = n_workers * envs_per_worker
        self._ctx = mp.get_context("spawn")
        self._procs: List[mp.Process] = []
        self._conns = []
        self.agents: List[str] = []
        self._closed = False
        try:
            for w in range(n_workers):
                seeds = [seed + w * envs_per_worker + j for j in range(envs_per_worker)]
                parent, child = self._ctx.Pipe(duplex=True)
                proc = self._ctx.Process(target=_worker_main, args=(child, spec, seeds), daemon=True,
                                         name=f"botcore-worker-{w}")
                proc.start()
                child.close()
                self._procs.append(proc)
                self._conns.append(parent)
            self._start_timeout = start_timeout
        except BaseException:
            self.close()
            raise

    # ---------------------------------------------------------------- messaging
    def _recv(self, w: int, timeout: Optional[float] = None):
        conn = self._conns[w]
        if timeout is not None and not conn.poll(timeout):
            raise CollectorError(f"worker {w} did not answer within {timeout:.0f}s (alive={self._procs[w].is_alive()})")
        try:
            status, payload = conn.recv()
        except EOFError as exc:
            raise CollectorError(f"worker {w} exited unexpectedly (exitcode={self._procs[w].exitcode})") from exc
        if status == "error":
            raise CollectorError(f"worker {w} crashed:\n{payload}")
        return payload

    def _broadcast(self, cmd: str, payloads: Optional[Sequence[Any]] = None, timeout: Optional[float] = None):
        for w, conn in enumerate(self._conns):
            conn.send((cmd, None if payloads is None else payloads[w]))
        return [self._recv(w, timeout) for w in range(self.n_workers)]

    # ---------------------------------------------------------------- API
    def reset(self) -> np.ndarray:
        replies = self._broadcast("reset", timeout=self._start_timeout)
        self.agents = list(replies[0][0])
        return np.concatenate([obs for _, obs in replies], axis=0)

    def env_indices(self, workers: Sequence[int]) -> np.ndarray:
        e = self.envs_per_worker
        return np.concatenate([np.arange(w * e, (w + 1) * e) for w in workers])

    def send_step(self, workers: Sequence[int], actions: np.ndarray) -> None:
        """Start stepping the envs of `workers`; `actions` covers exactly those envs, in worker order."""
        e = self.envs_per_worker
        for k, w in enumerate(workers):
            self._conns[w].send(("step", actions[k * e:(k + 1) * e]))

    def recv_step(self, workers: Sequence[int]) -> StepResult:
        """Collect the results of `send_step` for the same workers. Env indices in the result are local
        to the group (use `env_indices(workers)` to map them back)."""
        e = self.envs_per_worker
        replies = [self._recv(w) for w in workers]
        final_obs: Dict[int, np.ndarray] = {}
        for k, reply in enumerate(replies):
            for i, fo in reply[4].items():
                final_obs[k * e + i] = fo
        return StepResult(
            obs=np.concatenate([r[0] for r in replies], axis=0),
            rewards=np.concatenate([r[1] for r in replies], axis=0),
            terminated=np.concatenate([r[2] for r in replies], axis=0),
            truncated=np.concatenate([r[3] for r in replies], axis=0),
            final_obs=final_obs,
        )

    def step(self, actions: np.ndarray) -> StepResult:
        workers = list(range(self.n_workers))
        self.send_step(workers, actions)
        return self.recv_step(workers)

    def pop_stats(self) -> tuple[dict, List[dict]]:
        replies = self._broadcast("stats")
        raw: Dict[str, float] = {}
        weighted: Dict[str, float] = {}
        agent_steps = 0
        seconds = 0.0
        episodes: List[dict] = []
        for reward_stats, eps in replies:
            for stats in reward_stats:
                for k, v in stats["raw"].items():
                    raw[k] = raw.get(k, 0.0) + v
                for k, v in stats["weighted"].items():
                    weighted[k] = weighted.get(k, 0.0) + v
                agent_steps += stats["agent_steps"]
                seconds += stats["agent_seconds"]
            episodes.extend(eps)
        return {"raw": raw, "weighted": weighted, "agent_steps": agent_steps, "agent_seconds": seconds}, episodes

    def close(self, timeout: float = 15.0) -> None:
        if self._closed:
            return
        self._closed = True
        for w, conn in enumerate(self._conns):
            try:
                conn.send(("close", None))
            except Exception:
                pass
        for w, conn in enumerate(self._conns):
            try:
                if conn.poll(timeout):
                    conn.recv()
            except Exception:
                pass
            try:
                conn.close()
            except Exception:
                pass
        for proc in self._procs:
            proc.join(timeout)
            if proc.is_alive():
                proc.terminate()
                proc.join(5)

    def alive_workers(self) -> int:
        return sum(p.is_alive() for p in self._procs)

    def __enter__(self) -> "Collector":
        return self

    def __exit__(self, *exc) -> None:
        self.close()


# ----------------------------------------------------------------------------------------- rollout logic
@dataclass
class OpenTrajectory:
    agent_id: str
    env_index: int = -1
    obs: List[np.ndarray] = field(default_factory=list)
    actions: List[np.ndarray] = field(default_factory=list)
    log_probs: List[float] = field(default_factory=list)
    rewards: List[float] = field(default_factory=list)


@dataclass
class ClosedTrajectory:
    agent_id: str
    env_index: int
    obs: List[np.ndarray]
    actions: List[np.ndarray]
    log_probs: np.ndarray
    rewards: List[float]
    final_obs: np.ndarray
    truncated: bool  # True -> bootstrap from V(final_obs); False -> true terminal, next value 0


def role_map(n_envs: int, agents: Sequence[str], n_frozen_envs: int) -> np.ndarray:
    """[n_envs, n_agents] array of LEARNER/FROZEN.

    Frozen-opponent envs are spread evenly; the frozen side alternates between orange and blue so the
    learner plays both colours against frozen opponents.
    """
    roles = np.full((n_envs, len(agents)), LEARNER, dtype=object)
    if n_frozen_envs <= 0:
        return roles
    frozen_envs = np.linspace(0, n_envs - 1, n_frozen_envs).round().astype(int)
    for k, env_idx in enumerate(frozen_envs):
        frozen_team = "orange" if k % 2 == 0 else "blue"
        for j, agent in enumerate(agents):
            if agent.startswith(frozen_team):
                roles[env_idx, j] = FROZEN
    return roles


class RolloutBuffer:
    """Turns vectorised steps into per-agent trajectories with correct terminal/truncation boundaries."""

    def __init__(self, roles: np.ndarray, agents: Sequence[str]):
        self.roles = roles
        self.agents = list(agents)
        self.n_envs, self.n_agents = roles.shape
        self.learner_slots = [(i, j) for i in range(self.n_envs) for j in range(self.n_agents) if roles[i, j] == LEARNER]
        self._learner_agents = [[j for j in range(self.n_agents) if roles[i, j] == LEARNER] for i in range(self.n_envs)]
        self.open: Dict[tuple, OpenTrajectory] = {}
        self.closed: List[ClosedTrajectory] = []
        self.steps = 0
        self._new_all()

    def _new_all(self) -> None:
        for i, j in self.learner_slots:
            self.open[(i, j)] = OpenTrajectory(self.agents[j], i)

    def record(self, obs: np.ndarray, actions: np.ndarray, log_probs: np.ndarray, result: StepResult,
               env_indices: Optional[np.ndarray] = None) -> None:
        """Record one decision for every learner slot of the given environments (all if None).

        `obs`, `actions`, `log_probs` and `result` are indexed by position within `env_indices`; `obs` are the
        observations the actions were chosen from and `result` is what the environments returned.
        """
        if env_indices is None:
            env_indices = np.arange(self.n_envs)
        for k, i in enumerate(env_indices):
            done = bool(result.terminated[k] or result.truncated[k])
            for j in self._learner_agents[i]:
                traj = self.open[(i, j)]
                traj.obs.append(obs[k, j])
                traj.actions.append(actions[k, j:j + 1].astype(np.int64))
                traj.log_probs.append(float(log_probs[k, j]))
                traj.rewards.append(float(result.rewards[k, j]))
                self.steps += 1
                if done:
                    self._close((i, j), result.final_obs[k][j], truncated=bool(result.truncated[k]))

    def _close(self, slot: tuple, final_obs: np.ndarray, truncated: bool) -> None:
        traj = self.open[slot]
        if traj.obs:
            self.closed.append(ClosedTrajectory(
                traj.agent_id, traj.env_index, traj.obs, traj.actions, np.asarray(traj.log_probs, dtype=np.float32),
                traj.rewards, final_obs, truncated,
            ))
        self.open[slot] = OpenTrajectory(traj.agent_id, traj.env_index)

    def finish(self, current_obs: np.ndarray) -> List[ClosedTrajectory]:
        """End of rollout: cut every unfinished trajectory and bootstrap it from the observation the policy
        would act on next (an artificial truncation, not a terminal state)."""
        for i, j in self.learner_slots:
            self._close((i, j), current_obs[i, j], truncated=True)
        out, self.closed = self.closed, []
        return out


def run_rollout(collector: Collector, obs: np.ndarray, roles: np.ndarray, n_steps: int,
                act_learner: Callable[[np.ndarray], tuple[np.ndarray, np.ndarray]],
                act_frozen: Optional[Callable[[np.ndarray], np.ndarray]] = None,
                pipeline: bool = True):
    """Collect `n_steps` decisions in every environment.

    With `pipeline` (and >= 2 workers) the workers are split into two groups: while one group simulates, the
    parent receives, records and runs inference for the other. Every environment still takes exactly
    `n_steps` decisions, all from the same (current) policy, so this changes throughput, not the data.

    Returns (trajectories, next_obs, timing dict). `next_obs` must be passed to the next call so episodes
    continue across iterations (no forced reset at iteration boundaries).
    """
    buffer = RolloutBuffer(roles, collector.agents)
    if (roles == FROZEN).any() and act_frozen is None:
        raise ValueError("roles contain frozen agents but no frozen policy was supplied")
    obs = obs.copy()
    actions = np.zeros(roles.shape, dtype=np.int64)
    log_probs = np.zeros(roles.shape, dtype=np.float32)
    workers = list(range(collector.n_workers))
    groups = [workers[0::2], workers[1::2]] if pipeline and len(workers) >= 2 else [workers]
    group_envs = [collector.env_indices(g) for g in groups]
    timing = {"inference_s": 0.0, "env_wait_s": 0.0}

    def act(envs: np.ndarray) -> None:
        t0 = time.perf_counter()
        sub_roles = roles[envs]
        sub_obs = obs[envs]
        sub_actions = np.zeros(sub_roles.shape, dtype=np.int64)
        sub_logp = np.zeros(sub_roles.shape, dtype=np.float32)
        learner = sub_roles == LEARNER
        a, lp = act_learner(sub_obs[learner])
        sub_actions[learner] = a
        sub_logp[learner] = lp
        if (~learner).any():
            sub_actions[~learner] = act_frozen(sub_obs[~learner])
        actions[envs] = sub_actions
        log_probs[envs] = sub_logp
        timing["inference_s"] += time.perf_counter() - t0

    for g, envs in zip(groups, group_envs):
        act(envs)
        collector.send_step(g, actions[envs])
    for step in range(n_steps):
        for g, envs in zip(groups, group_envs):
            t0 = time.perf_counter()
            result = collector.recv_step(g)
            timing["env_wait_s"] += time.perf_counter() - t0
            buffer.record(obs[envs], actions[envs], log_probs[envs], result, envs)
            obs[envs] = result.obs
            if step < n_steps - 1:
                act(envs)
                collector.send_step(g, actions[envs])
    trajectories = buffer.finish(obs)
    return trajectories, obs, {**timing, "learner_steps": buffer.steps}
